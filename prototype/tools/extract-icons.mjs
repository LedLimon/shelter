const root = fileURLToPath(new URL("..", import.meta.url));
const icons = join(root, "../node_modules/lucide-react/dist/esm/icons");

const attrs = (props) =>
  Object.entries(props)
    .filter(([name]) => name !== "key")
    .map(([name, value]) => `${name}="${value}"`)
    .join(" ");

const entries = [];
for (const name of [...NAMES].sort()) {
  const { __iconData } = await import(
    pathToFileURL(join(icons, `${name}.mjs`)).href
  );
  const body = __iconData.node
    .map(([tag, props]) => `<${tag} ${attrs(props)}/>`)
    .join("");
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(body)},`);
}

await writeFile(
  join(root, "src/js/05-icons.js"),
  `// Generated by tools/extract-icons.mjs from lucide (ISC licence). Do not edit by hand.\nconst ICONS = {\n${entries.join("\n")}\n};\n`,
);
console.log(`${entries.length} icons`);
